def main():
    with open('data/drugs-final.json', 'r') as f:
        drugs = json.load(f)

    fixed = 0
    for drug in drugs:
        if drug['name'] in FIXES:
            drug['renalDosing'] = FIXES[drug['name']]
            fixed += 1

    with open('data/drugs-final.json', 'w') as f:
        json.dump(drugs, f, ensure_ascii=False, indent=2)

    print(f"Fixed {fixed} drugs out of {len(FIXES)} corrections")
    if fixed != len(FIXES):
        print("WARNING: Some drug names did not match!")
        matched = {d['name'] for d in drugs}
        for name in FIXES:
            if name not in matched:
                print(f"  NOT FOUND: {name}")


if __name__ == '__main__':
    main()
