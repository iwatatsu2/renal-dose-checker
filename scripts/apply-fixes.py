import json

def classify(dose):
    if not dose: return "unknown"
    if any(k in dose for k in ['禁忌','使用しない','投与しない','推奨しない']): return "contraindicated"
    if any(k in dose for k in ['常用量','減量不要','用量調節不要','通常量']): return "normal"
    if any(k in dose for k in ['減量','半量','50%','75%','1/2','1/3','1/4','1/5']): return "reduce"
    if any(k in dose for k in ['慎重','注意','低用量','要注意','モニタリング']): return "caution"
    if any(k in dose for k in ['mg','回','日']): return "reduce"
    return "unknown"

def t(range_str, dose):
    return {"range": range_str, "dose": dose, "status": classify(dose)}

